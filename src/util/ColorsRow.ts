export default function ColorsRow(row: number) {
  switch (row) {
    case 0:
      return "#FF8C94";
    case 1:
      return "#FFB6A0";
    case 2:
      return "#FEEFAD";
    case 3:
      return "#A8DAD0";
    case 4:
      return "#9BBFE8";
    case 5:
      return "#E0C2E8";
    case 6:
      return "#B19F9F";
  }
}
